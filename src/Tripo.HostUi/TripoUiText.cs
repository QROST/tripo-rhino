    private static string _language = "en";

    public static string Language => Volatile.Read(ref _language);

    /// <summary>Rhino's valid interface language wins, including English on a Chinese system.</summary>
    public static string ResolveLanguage(int? rhinoLanguageId, CultureInfo? systemUiCulture)
    {
        CultureInfo? selected = null;
        if (rhinoLanguageId is > 0 and not 127)
        {
            try { selected = CultureInfo.GetCultureInfo(rhinoLanguageId.Value); }
            catch (CultureNotFoundException) { }
        }
        if (selected is null || string.IsNullOrEmpty(selected.Name)) selected = systemUiCulture;
        return selected?.TwoLetterISOLanguageName == "zh" ? "zh-CN" : "en";
    }

    /// <summary>Called once when the plugin loads. Background tasks share this UI language, not their thread culture.</summary>
    public static void Initialize(int? rhinoLanguageId, CultureInfo? systemUiCulture) =>
        Volatile.Write(ref _language, ResolveLanguage(rhinoLanguageId, systemUiCulture));

    public static string Get(string english) => Get(english, Language);

    public static string Get(string english, string language)
    {
        ArgumentNullException.ThrowIfNull(english);
        return language == "zh-CN" && Chinese.TryGetValue(english, out string? translated) ? translated : english;
    }

    public static string Format(string englishTemplate, params object?[] values) =>
        string.Format(CultureInfo.CurrentCulture, Get(englishTemplate), values);

